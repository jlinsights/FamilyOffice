  /**
   * 질문에서 키워드 매칭하여 가장 적절한 응답 찾기
   */
  findBestMatch(query: string): string {
    const queryLower = query.toLowerCase();
    
    // 각 카테고리별 키워드 매칭 점수 계산
    const scores: { [key: string]: number } = {};
    
    for (const [category, data] of Object.entries(this.mockResponses)) {
      if (category === '기본') continue;
      
      let score = 0;
      for (const keyword of data.keywords) {
        if (queryLower.includes(keyword)) {
          score += keyword.length; // 긴 키워드일수록 더 정확한 매칭
        }
      }
      scores[category] = score;
    }
    
    // 가장 높은 점수의 카테고리 찾기
    const bestMatch = Object.entries(scores)
      .filter(([_, score]) => score > 0)
      .sort(([_, a], [__, b]) => b - a)[0];
    
    if (bestMatch) {
      return this.mockResponses[bestMatch[0] as keyof typeof this.mockResponses].response;
    }
    
    // 매칭되는 키워드가 없으면 기본 응답
    return this.mockResponses.기본.response;
  }

